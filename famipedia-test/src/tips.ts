  '写真を1枚撮らせてもらって、あとでページに追加しましょう',
  '写真やアルバムがあれば、一緒に見ながら話すと思い出しやすくなります',

  // 聞き方のコツ
  '話し言葉のままで大丈夫。「えーと」や方言も、AIが整えてくれます',
  '正確な年や数字を思い出せなくても大丈夫。「だいたい」で十分です',
  '答えに詰まったら、無理に聞かずに「スキップ」でも大丈夫です',
  '「すごいね」「知らなかった！」の一言で、話す人はもっと話したくなります',

